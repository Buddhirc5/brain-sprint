// Generates supabase/seed.sql from src/data/library.json (the starter question library).
// Run: node scripts/sb_gen_seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lib = JSON.parse(readFileSync(join(root, "src/data/library.json"), "utf8"));

const q = (v) => {
  const s = JSON.stringify(v);
  if (s.includes("$lib$")) throw new Error("library text contains the dollar-quote tag");
  return `$lib$${s}$lib$::jsonb`;
};
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

const rows = lib.map(
  (it, i) =>
    `  (${lit(it.id)}, ${lit(it.title)}, ${lit(it.topic || "")}, ${lit(it.industry === "bank" ? "bank" : "any")}, ${q(it.questions)}, ${q(it.answers)}, ${i + 1})`,
);

const sql = `-- =====================================================================
-- Ant Arena — seed (generated by scripts/sb_gen_seed.mjs — do not edit by hand)
-- Run after 0001 → 0003. Safe to run again (upserts).
-- =====================================================================

-- 1) starter question library (${lib.length} sets, ${lib.reduce((n, x) => n + x.questions.length, 0)} questions)
insert into public.library (id, title, topic, industry, questions, answers, ord) values
${rows.join(",\n")}
on conflict (id) do update set title = excluded.title, topic = excluded.topic, industry = excluded.industry,
  questions = excluded.questions, answers = excluded.answers, ord = excluded.ord;

-- 2) make yourself super admin (you'll sign in with email + password + an authenticator app) — EITHER uncomment and edit this line:
-- insert into public.super_admins (email) values ('YOUR-EMAIL@example.com');
-- OR run this in the SQL editor (not callable from the app):
-- select public.bootstrap_super_admin('YOUR-EMAIL@example.com');
`;

writeFileSync(join(root, "supabase/seed.sql"), sql);
console.log(`wrote supabase/seed.sql (${lib.length} library sets)`);
